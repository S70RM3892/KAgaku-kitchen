def empirical(c, h, o):
    m = min(x for x in (c, h, o) if x > 1e-9)
    r = [x / m for x in (c, h, o)]
    for k in range(1, 7):
        if all(abs(x * k - round(x * k)) < 0.05 for x in r):
            n = [round(x * k) for x in r]
            return ''.join(s + (str(v).translate(str.maketrans('0123456789', '₀₁₂₃₄₅₆₇₈₉')) if v > 1 else '') for s, v in zip('CHO', n) if v)
    raise ValueError(r)


def molform(emp, mw):
    # 組成式（元素 → 個数）と分子量から分子式をつくる
    mass = {'C': C, 'H': H, 'O': O}
    k = mw / sum(mass[e] * n for e, n in emp.items())
    assert abs(k - round(k)) < 1e-9
    sub = str.maketrans('0123456789', '₀₁₂₃₄₅₆₇₈₉')
    return ''.join(e + (str(n * round(k)).translate(sub) if n * round(k) > 1 else '') for e, n in emp.items())


