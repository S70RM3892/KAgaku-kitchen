def distract(p, ans):
    f = lambda v: fmt(v, p['sig'], p['unit'], p['sign'], p['dec'])
    out = []
    for w in p['wrong']:
        s = f(w)
        if s != ans and s not in out:
            out.append(s)
    if isinstance(p['val'], str):
        return out
    v = p['val']
    if p['kind'] == 'add':
        auto = [v + 1, v - 1, v + 0.3, v - 0.3, v + 2, v - 2, v + 0.7, v - 0.7]
    else:
        auto = ([-v] if (p['sign'] or v < 0) else []) + [v * 2, v / 2, v * 10, v / 10, v * 3, v / 3, v * 5, v / 5, v * 4, v / 4]
    for w in auto:
        if len(out) >= 5:
            break
        if p['kind'] == 'add' and w < 0:
            continue
        s = f(w)
        if s != ans and s not in out:
            out.append(s)
    return out[:5]


def main():
    bad, rows = 0, []
    for i, p in enumerate(P):
        try:
            p['val'] = p['calc']()
        except Exception as e:
            print(f'計算できない [{i}] {p["q"]}: {e}')
            bad += 1
            continue
        ans = fmt(p['val'], p['sig'], p['unit'], p['sign'], p['dec'])
        if ans != p['exp'].replace('-', '−') and ans != p['exp']:
            print(f'× 合わない [{i}] {p["q"]}\n   計算 {ans}（値 {p["val"]}）  手で出した答え {p["exp"]}')
            bad += 1
            continue
        ans = ans.replace('-', '−')
        ws = [w.replace('-', '−') for w in distract(p, ans)]
        if len(ws) < 3 or ans in ws or len(set(ws)) != len(ws):
            print(f'× まちがいの選択肢が足りない・重なる [{i}] {p["q"]}: {ws}')
            bad += 1
            continue
