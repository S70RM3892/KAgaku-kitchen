def fmt(v, sig=2, unit='', sign=False, dec=None):
    """値を有効数字 sig 桁（または小数 dec 桁）で四捨五入して表示用の文字列にする"""
    if isinstance(v, str):
        return v
    if sig == 0:
        s = str(int(Decimal(f'{v:.10g}').quantize(Decimal(1), rounding=ROUND_HALF_UP)))
    elif dec is not None:
        s = str(Decimal(f'{v:.10g}').quantize(Decimal(1).scaleb(-dec), rounding=ROUND_HALF_UP))
    else:
        d = Decimal(f'{v:.10g}')
        if d == 0:
            return '0' + unit
        e = d.adjusted()
        r = d.quantize(Decimal(1).scaleb(e - sig + 1), rounding=ROUND_HALF_UP)
        e = r.adjusted()
        r = r.quantize(Decimal(1).scaleb(e - sig + 1), rounding=ROUND_HALF_UP)
        if -2 <= e <= 3 and e + 1 <= max(sig, 1) + (0 if e + 1 > sig else 9):
            # ふつうの小数で書ける範囲（整数部の桁数が有効数字を超えるときは指数で書く）
            s = f'{r:.{max(0, sig - 1 - e)}f}' if e + 1 <= sig else None
        else:
            s = None
        if s is None:
            m = r.scaleb(-e)
            s = f'{m:.{sig - 1}f}×10' + str(e).translate(SUP)
    if s.startswith('-'):
        s = '−' + s[1:]
    elif sign:
        s = '+' + s
    return s + unit


